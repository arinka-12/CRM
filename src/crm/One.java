    void setMenuHighlight(javax.swing.JButton menuAktif) {
    // 1. Kembalikan semua tombol ke tampilan standar (tulisan hitam, tanpa background)
        
    javax.swing.JButton[] semuaMenu = {jButton1, jButton2, jButton3, jButton4, jButton5, jButton6};
    menuAktif.setContentAreaFilled(false);    
    for (javax.swing.JButton btn : semuaMenu) {
        btn.setFocusPainted(false);
        btn.setBackground(new java.awt.Color(254, 211, 108)); // Warna orange sidebar Anda
        btn.setForeground(java.awt.Color.BLACK); // Teks hitam polos
        }
    
    // 2. Berikan warna sorotan hanya untuk tombol yang sedang diklik
        menuAktif.setContentAreaFilled(true);
        menuAktif.setBackground(new java.awt.Color(157, 110, 17)); // Contoh cokelat/orange tua aktif
        menuAktif.setForeground(java.awt.Color.WHITE); // Teks jadi putih agar kontras
}

